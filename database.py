@contextmanager
def connect():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        try:
            with psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10) as con:
                yield con
        except psycopg.IntegrityError as exc:
            raise IntegrityError from exc
        return

    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(DB_PATH, timeout=20)
    con.row_factory = sqlite3.Row
    con.execute('PRAGMA foreign_keys=ON')
    try:
        yield con
        con.commit()
    except sqlite3.IntegrityError as exc:
        con.rollback()
        raise IntegrityError from exc
    except Exception:
        con.rollback()
        raise
    finally:
        con.close()

SCHEMA = '''
        CREATE TABLE IF NOT EXISTS products (
          id INTEGER PRIMARY KEY, sku TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
          category TEXT NOT NULL, variant TEXT NOT NULL, brand TEXT, specification TEXT,
          unit TEXT NOT NULL, cost REAL NOT NULL CHECK(cost>=0), price REAL NOT NULL CHECK(price>=0),
          minimum REAL NOT NULL CHECK(minimum>=0), stock REAL NOT NULL DEFAULT 0 CHECK(stock>=0));
        CREATE TABLE IF NOT EXISTS contacts (
          id INTEGER PRIMARY KEY, kind TEXT NOT NULL, name TEXT NOT NULL,
          phone TEXT, email TEXT, address TEXT, gstin TEXT);
        CREATE TABLE IF NOT EXISTS projects (
          id INTEGER PRIMARY KEY, name TEXT NOT NULL, customer_id INTEGER REFERENCES contacts(id),
          capacity REAL, stage TEXT, value REAL, notes TEXT);
        CREATE TABLE IF NOT EXISTS movements (
          id INTEGER PRIMARY KEY, created TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
          product_id INTEGER NOT NULL REFERENCES products(id), kind TEXT NOT NULL,
          quantity REAL NOT NULL CHECK(quantity>0), rate REAL NOT NULL CHECK(rate>=0),
          contact_id INTEGER REFERENCES contacts(id), project_id INTEGER REFERENCES projects(id),
          reference TEXT NOT NULL, notes TEXT, destination TEXT, source TEXT);
'''


def init():
    with connect() as c:
        if DATABASE_URL:
            ready = c.execute('''
                SELECT to_regclass('products') IS NOT NULL
                   AND to_regclass('contacts') IS NOT NULL
                   AND to_regclass('projects') IS NOT NULL
                   AND strpos(pg_get_viewdef(to_regclass('warehouse_products')), 'Meters') > 0
                   AND (
                       SELECT COUNT(*) FROM pg_attribute
                       WHERE attrelid = to_regclass('movements')
                         AND attname IN ('destination', 'source') AND NOT attisdropped
                   ) = 2 AS ready
            ''').fetchone()['ready']
            if ready:
                return

            # Serialize first-time setup across app sessions and the import command.
            c.execute('SELECT pg_advisory_xact_lock(560941804)')
            schema = SCHEMA.replace('id INTEGER PRIMARY KEY', 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
            schema = schema.replace(' REAL', ' DOUBLE PRECISION')
            schema = schema.replace('DEFAULT CURRENT_TIMESTAMP', "DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')")
            for statement in schema.strip().rstrip(';').split(';'):
                c.execute(statement)
            c.execute('ALTER TABLE movements ADD COLUMN IF NOT EXISTS destination TEXT')
            c.execute('ALTER TABLE movements ADD COLUMN IF NOT EXISTS source TEXT')
            c.execute('''
                CREATE OR REPLACE VIEW warehouse_products AS
                SELECT name AS product, category, stock AS in_stock,
                       CASE unit WHEN 'Nos' THEN 'Pieces' WHEN 'Metres' THEN 'Meters' ELSE unit END AS unit
                FROM products
            ''')
        else:
            c.executescript(SCHEMA)
            c.execute('BEGIN IMMEDIATE')
            columns = {column['name'] for column in c.execute('PRAGMA table_info(movements)')}
            if 'destination' not in columns:
                c.execute('ALTER TABLE movements ADD COLUMN destination TEXT')
            if 'source' not in columns:
                c.execute('ALTER TABLE movements ADD COLUMN source TEXT')


def query(connection, sql, params=()):
    return connection.execute(sql.replace('?', '%s') if DATABASE_URL else sql, params)

def rows(sql, params=()):
    with connect() as c:
        return [dict(r) for r in query(c, sql, params)]

def execute(sql, params=()):
    with connect() as c:
        if DATABASE_URL:
            if sql.lstrip().upper().startswith('INSERT INTO'):
                return query(c, sql + ' RETURNING id', params).fetchone()['id']
            query(c, sql, params)
            return None
        return query(c, sql, params).lastrowid


def lock_product_catalog(connection):
    if DATABASE_URL:
        connection.execute('SELECT pg_advisory_xact_lock(560941805)')
    else:
        connection.execute('BEGIN IMMEDIATE')


def product_name_key(name):
    return ' '.join(name.split()).casefold()


def matching_products(connection, name, category):
    candidates = query(connection, 'SELECT id,name,unit FROM products WHERE category=?', (category,))
    return [product for product in candidates
            if product_name_key(product['name']) == product_name_key(name)]


def merge_duplicate_products(products):
    expected = sorted(products, key=lambda product: product['id'])
    ids = tuple(product['id'] for product in expected)
    if len(set(ids)) < 2:
        raise ValueError('Select at least two duplicate rows.')
    with connect() as c:
        lock_product_catalog(c)
        placeholders = ','.join('?' for _ in ids)
        lock = ' FOR UPDATE' if DATABASE_URL else ''
        current = query(c, f'''SELECT id,sku,name,category,unit,stock FROM products
                               WHERE id IN ({placeholders}) ORDER BY id{lock}''', ids).fetchall()
        fields = ('id', 'sku', 'name', 'category', 'unit', 'stock')
        if [tuple(p[f] for f in fields) for p in current] != [tuple(p[f] for f in fields) for p in expected]:
            raise ValueError('The warehouse rows changed. Close this dialog and review the current balances.')
        if len({(product_name_key(p['name']), p['category'], p['unit']) for p in current}) != 1:
            raise ValueError('The product names, categories, and units must match.')
        keep_id, *duplicate_ids = ids
        query(c, 'UPDATE products SET stock=? WHERE id=?', (sum(p['stock'] for p in current), keep_id))
        for duplicate_id in duplicate_ids:
            query(c, 'UPDATE movements SET product_id=? WHERE product_id=?', (keep_id, duplicate_id))
            query(c, 'DELETE FROM products WHERE id=?', (duplicate_id,))


def edit_product(product_id, sku, name, category):
    name = ' '.join(name.split())
    if not name:
        raise ValueError('Enter the product name.')
    with connect() as c:
        lock_product_catalog(c)
        if any(product['id'] != product_id for product in matching_products(c, name, category)):
            raise ValueError('A product with this name already exists in that category.')
        updated = query(c, '''UPDATE products SET name=?,category=?
                              WHERE id=? AND sku=? RETURNING id''',
                        (name, category, product_id, sku)).fetchone()
        if updated is None:
            raise ValueError('That product no longer exists.')


def add_product(sku, name, category, unit, quantity, *, source=None):
    if quantity is None or quantity <= 0:
        raise ValueError('Enter how many came in.')
    name = ' '.join(name.split())
    if not name:
        raise ValueError('Enter the product name.')
    with connect() as c:
        lock_product_catalog(c)
        matches = matching_products(c, name, category)
        if len(matches) > 1:
            raise ValueError('More than one warehouse row has this name. Review the matching rows in Warehouse stock.')
        if matches:
            product = matches[0]
            if unit != product['unit']:
                raise ValueError(f"This product already uses {product['unit']}. Select the same unit or use Receive stock.")
            updated = query(c, '''UPDATE products SET stock=stock+?
                                  WHERE id=? AND name=? AND unit=? RETURNING id''',
                            (quantity, product['id'], product['name'], unit)).fetchone()
            if updated is None:
                raise ValueError('The matching product changed. Try again.')
            query(c, '''INSERT INTO movements(product_id,kind,quantity,rate,reference,source)
                        VALUES(?,'Receipt',?,0,'Receive stock',?)''', (product['id'], quantity, source))
            return False
        insert = '''INSERT INTO products(sku,name,category,variant,unit,cost,price,minimum,stock)
                    VALUES(?,?,?,'Unspecified',?,0,0,0,?)'''
        params = (sku, name, category, unit, quantity)
        if DATABASE_URL:
            product_id = query(c, insert + ' RETURNING id', params).fetchone()['id']
        else:
            product_id = query(c, insert, params).lastrowid
        query(c, '''INSERT INTO movements(product_id,kind,quantity,rate,reference,source)
                    VALUES(?,'Receipt',?,0,'First delivery',?)''', (product_id, quantity, source))
        return True


def delete_mistaken_product(product_id, sku):
    with connect() as c:
        if not DATABASE_URL:
            c.execute('BEGIN IMMEDIATE')
        lock = ' FOR UPDATE' if DATABASE_URL else ''
        product = query(c, 'SELECT stock FROM products WHERE id=? AND sku=?' + lock, (product_id, sku)).fetchone()
        if product is None:
            raise ValueError('That product no longer exists.')
        movements = query(c, '''
            SELECT kind, quantity, reference FROM movements WHERE product_id=? LIMIT 2
        ''', (product_id,)).fetchall()
        if movements:
            entry = movements[0]
            if (len(movements) != 1 or entry['kind'] != 'Receipt' or
                    entry['reference'] != 'First delivery' or entry['quantity'] != product['stock']):
                raise ValueError('This product has stock history. You can correct its name.')
            query(c, 'DELETE FROM movements WHERE product_id=?', (product_id,))
        elif product['stock'] != 0:
            raise ValueError('This product still has stock. You can correct its name.')
        query(c, 'DELETE FROM products WHERE id=? AND sku=?', (product_id, sku))


STOCK_HISTORY_SELECT = '''
    SELECT m.created AS "Time (UTC)", p.name AS "Product", m.kind AS "Movement",
           m.quantity AS "Quantity", p.unit AS "Unit",
           CASE WHEN m.kind IN ('Issue', 'Supplier return')
                THEN COALESCE(m.destination, j.name, c.name, 'Not recorded') END AS "Sent to",
           CASE WHEN m.kind IN ('Receipt', 'Customer return')
                THEN COALESCE(m.source, c.name, 'Not recorded') END AS "Received from"
    FROM movements m JOIN products p ON p.id=m.product_id
    LEFT JOIN projects j ON j.id=m.project_id LEFT JOIN contacts c ON c.id=m.contact_id
'''
STOCK_HISTORY = STOCK_HISTORY_SELECT + ' ORDER BY m.id DESC'


def dispatch_history():
    return rows(STOCK_HISTORY_SELECT + """
        WHERE m.kind IN ('Issue', 'Supplier return')
        ORDER BY m.id DESC
    """)


def receipt_history():
    return rows(STOCK_HISTORY_SELECT + """
        WHERE m.kind IN ('Receipt', 'Customer return')
        ORDER BY m.id DESC
    """)


STOCK_TOTALS = '''WITH movement_totals AS (
    SELECT product_id,
           SUM(CASE WHEN kind IN ('Receipt', 'Customer return') THEN quantity ELSE 0 END) AS stock_in,
           SUM(CASE WHEN kind IN ('Issue', 'Supplier return') THEN quantity ELSE 0 END) AS stock_out,
           MAX(CASE WHEN kind IN ('Receipt', 'Customer return') THEN id END) AS latest_receipt_id
    FROM movements GROUP BY product_id
)
SELECT p.id,p.sku,p.name,p.category,p.variant,p.specification,p.unit,p.minimum,p.stock,
       COALESCE(m.stock_in, 0) AS stock_in, COALESCE(m.stock_out, 0) AS stock_out,
       latest.quantity AS latest_received
FROM products p LEFT JOIN movement_totals m ON m.product_id=p.id
LEFT JOIN movements latest ON latest.id=m.latest_receipt_id
ORDER BY p.category,p.name,p.sku'''


def overview_products():
    return rows(STOCK_TOTALS)


def inventory_snapshot():
    with connect() as c:
        c.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY' if DATABASE_URL else 'BEGIN')
        products = [dict(row) for row in c.execute(STOCK_TOTALS)]
        active_projects = c.execute(
            "SELECT COUNT(*) AS total FROM projects WHERE stage IS NULL OR stage NOT IN ('Completed','Lost')"
        ).fetchone()['total']
        activity = [dict(row) for row in c.execute(STOCK_HISTORY + ' LIMIT 10')]
    totals_by_unit = {}
    for product in products:
        unit = product['unit']
        totals = totals_by_unit.setdefault(unit, {'Unit': unit, 'Stock in': 0, 'Stock out': 0, 'On hand': 0})
        totals['Stock in'] += product['stock_in']
        totals['Stock out'] += product['stock_out']
        totals['On hand'] += product['stock']

    return products, active_projects, [totals_by_unit[unit] for unit in sorted(totals_by_unit)], activity

def move(product_id, kind, quantity, rate, contact_id, project_id, reference, notes, *, destination=None, source=None):
    if kind not in ('Receipt', 'Issue', 'Customer return', 'Supplier return'):
        raise ValueError('Invalid movement type.')
    if quantity <= 0 or rate < 0 or not reference.strip():
        raise ValueError('Enter a positive quantity, valid rate, and reference.')
    change = quantity if kind in ('Receipt', 'Customer return') else -quantity
    with connect() as c:
        if not DATABASE_URL:
            c.execute('BEGIN IMMEDIATE')
        result = query(c, 'UPDATE products SET stock=stock+? WHERE id=? AND stock+?>=0',
                           (change, product_id, change))
        if result.rowcount != 1:
            raise ValueError('Insufficient stock. Refresh and check available quantity.')
        query(c, '''INSERT INTO movements(product_id,kind,quantity,rate,contact_id,project_id,reference,notes,destination,source)
                     VALUES(?,?,?,?,?,?,?,?,?,?)''',
                  (product_id, kind, quantity, rate, contact_id, project_id, reference.strip(), notes, destination, source))
